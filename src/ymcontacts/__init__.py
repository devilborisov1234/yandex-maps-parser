"""Сбор организаций и контактов из Яндекс Карт.

Пакет разделён на слои, чтобы смена источника не требовала переписывания:

    config      — настройки (город, темп, пути), читаются из .env
    models      — структуры данных (карточка организации, задача, сводная запись)
    normalize   — приведение телефонов, почт, ссылок и названий к каноническому виду
    storage     — SQLite: карточки, очередь задач, состояние источников, индекс кэша
    pacing      — темп запросов: задержки, передышки, лимиты, остановка
    rawcache    — кэш сырых JSON-ответов на диске (gzip)
    fetcher     — HTTP-доставка: сессия, куки, ретраи, circuit breaker
    grid        — разбиение города на bbox-ячейки
    sources     — адаптеры источников (Яндекс HTTP и Яндекс браузерный)
    sites       — этап 2: обход сайтов организаций, извлечение почт и мессенджеров
    merge       — склейка нескольких карточек одной организации (филиалы)
    export      — выгрузка CSV
    runner      — оркестратор прогона: очередь, ретраи, отчёт, graceful shutdown
    cli         — точка входа: команды discover / sweep / sites / export / report
"""

